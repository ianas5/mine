def _text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _inspection() -> dict:
    if "inspection" not in _CACHE:
        _CACHE["inspection"] = json.loads(_text(INSPECTION_PATH))
    return _CACHE["inspection"]  # type: ignore[return-value]


def _cases() -> dict:
    if "cases" not in _CACHE:
        _CACHE["cases"] = json.loads(_text(GATE_B_CASES_PATH))
