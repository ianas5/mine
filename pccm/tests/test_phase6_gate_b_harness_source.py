def test_07_no_identity_row_number_is_restated() -> None:
    """Rows are asked for by MEANING. A bare row integer would be a second copy."""
    code = _executable(PHASE6)
    rows = _inspection()["sim_data"]["run_identity"]["rows"]
    for key, row in rows.items():
        if row < 10:
            # A single digit is shared with every count and index in the file,
            # and cannot build an address on its own: a literal A1 reference and
            # a quoted column letter are both already refused above, so there is
            # nothing for a bare 8 to be concatenated with.
            continue
        # `(?<![\w.\-])` so "Step-13" is not read as the row 13.
        assert not re.search(rf"(?<![\w.\-]){row}(?![\w.\-])", code), (
            f"the row number {row} ({key}) is restated in executable code"
        )


