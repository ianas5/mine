def _sim_constants() -> dict[str, str]:
    """`SIM_*` and `NM_*` constants, as written by the generator."""
    if "constants" not in _CACHE:
        found: dict[str, str] = {}
        for module in ("modSimContract.bas", "modConstants.bas"):
            for line in _text(BUILD / "vba" / module).splitlines():
                match = re.match(
                    r"Public Const (\w+) As \w+ = (.+?)(?:\s+'.*)?$", line.strip()
                )
                if match:
                    found[match.group(1)] = match.group(2).strip().strip('"')
        _CACHE["constants"] = found
    return _CACHE["constants"]  # type: ignore[return-value]


def _executable(path: Path) -> str:
    """PowerShell source with the block comment and every `#` line removed.

    A rule about what the harness may not RESTATE has to be checked against what
    it EXECUTES. Prose that explains why an address is not spelled here would
    otherwise trip the rule that it is not spelled here.
    """
    body = re.sub(r"<#.*?#>", "", _text(path), flags=re.S)
    return "\n".join(
        line for line in body.splitlines() if not line.lstrip().startswith("#")
    )


def _git_show(revision: str, relative: str) -> bytes:
    return subprocess.run(
        ["git", "show", f"{revision}:{relative}"],
        cwd=REPO_ROOT, check=True, stdout=subprocess.PIPE,
    ).stdout


