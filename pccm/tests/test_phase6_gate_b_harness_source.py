def test_34b_the_declared_scenario_set_covers_every_required_and_recorded_id() -> None:
    """`Get-Phase6ScenarioIds` is the declaration the preflight validates against.

    Scoped to that function's own return block: an ID that still appears
    elsewhere in the file - in the required list, or in the Add-Phase6Result
    call that records it - is NOT declared, and the preflight would refuse it on
    Windows. A whole-file search would find those other mentions and pass.
    """
    code = _executable(PHASE6)
    block = code.split("function Get-Phase6ScenarioIds")[1].split("\nfunction ")[0]
    declared = set(re.findall(r"'(P6-[A-Z0-9-]+)'", block))
    for identifier in REQUIRED_SCENARIOS:
        assert identifier in declared, f"{identifier} is not declared"
    assert "P6-FIN" in declared
    required_block = code.split("function Get-Phase6RequiredScenarioIds")[1].split(
        "\nfunction ")[0]
    required = set(re.findall(r"'(P6-[A-Z0-9-]+)'", required_block))
    assert required == set(REQUIRED_SCENARIOS), sorted(required ^ set(REQUIRED_SCENARIOS))
    assert required <= declared, sorted(required - declared)
    recorded = set(re.findall(r"Add-Phase6Result '(P6-[A-Z0-9-]+)'", code))
    recorded |= set(re.findall(r"-Id '(P6-[A-Z0-9-]+)'", code))
    assert recorded <= declared, sorted(recorded - declared)


