def test_05_no_a1_address_literal_appears_in_executable_code() -> None:
    """Every cell the harness touches is named by the projection, never spelled.

    A quoted A1 reference in executable PowerShell would be a SECOND reader of
    the `_SimData` layout, which is the whole reason the projection exists.
    """
    code = _executable(PHASE6)
    literals = re.findall(
        r"""['"]([A-Z]{1,2}[0-9]{1,5}(?::[A-Z]{1,2}[0-9]{1,5})?)['"]""", code
    )
    assert literals == [], f"restated addresses: {sorted(set(literals))}"
    assert not re.search(r"\.Range\(\s*['\"]", code), (
        "a Range call was given a literal address"
    )


