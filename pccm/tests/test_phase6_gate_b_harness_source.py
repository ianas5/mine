def test_25_the_four_sampling_mechanisms_are_covered() -> None:
    """No single existing fixture reaches all four, so four existing ones are used.

    Reported rather than papered over: this is why the corpus has four cases and
    not one, and why no fifth fixture was invented.
    """
    families = set()
    for identifier, mechanism, _golden in GATE_B_PARITY_PLAN_CASES:
        model = {case["id"]: case for case in PLAN_CASES}[identifier]["model"]
        for driver in model["cost_lines"]:
            families.add(driver["distribution"])
        for driver in model["risks"]:
            families.add(driver["distribution"])
            assert driver["probability"] is not None, mechanism
        assert mechanism
    assert {"Triangular", "Beta-PERT", "Uniform"} <= families, families
    assert any(model_has_risk() for model_has_risk in [
        lambda: any(
            {case["id"]: case for case in PLAN_CASES}[identifier]["model"]["risks"]
            for identifier, _m, _g in GATE_B_PARITY_PLAN_CASES
        )
    ]), "no case reaches the Bernoulli occurrence primitive"


def test_26_no_parity_fixture_is_degenerate() -> None:
    """A min == max driver draws the same value under every seed.

    Plan case 30 is exactly that - three Uniform drivers with min == max - and a
    parity case built on it would pass whatever the RNG did.
    """
    known = {case["id"]: case for case in PLAN_CASES}
    for identifier, mechanism, _golden in GATE_B_PARITY_PLAN_CASES:
        model = known[identifier]["model"]
        drivers = list(model["cost_lines"]) + list(model["risks"])
        assert drivers, identifier
        for driver in drivers:
            assert driver["min_value"] != driver["max_value"], (
                f"plan case {identifier} ({mechanism}) has a degenerate driver"
            )


