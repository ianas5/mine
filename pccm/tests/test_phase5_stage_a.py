# --- helper-level vectors, classified from exact arithmetic ------------------
def _classify(exact: Fraction):
    """`(kind, correctly rounded Double)` for an exact value, range-tested EXACTLY.

    `abs(exact) <= Fraction(MAX_DOUBLE)` is tested before `float(exact)`, because a
    value can exceed `MAX_DOUBLE` and still round down to it.
    """
    if abs(exact) > _EXACT_MAX:
        return "out-of-range", None
    target = float(exact)
    if exact != 0 and target == 0.0:
        return "collapsed", None
    return "value", target


def _check_helper_vector(
    ledger: _Ledger, path: str, entry: dict, exact: Fraction,
    tier_one=None, classify_zero: bool = False,
) -> None:
    """One helper-level vector, judged by the accepted two-tier rule.

    TIER 1 OWNS ITS RESULT. `[1e16, 1, -1e16]` sums to `0.0` in canonical order and
    to `1.0` in exact arithmetic, and `0.0` is the required answer - the corpus
    would be wrong to carry the exact value there. So the reference is tier 1 where
    tier 1 produced a value, and the exact classification only where it did not.

    `classify_zero` is the one extra rule the convex statistics carry: a
    NON-DEGENERATE statistic that evaluates to exactly zero is not accepted on
    sight, because the exact value may be non-zero with no usable Double.
    """
    if tier_one is not None and not (classify_zero and tier_one == 0.0):
        kind, target = "value", tier_one
    else:
        kind, target = _classify(exact)

    if "expected_refusal" in entry:
        assert kind != "value", (
            f"{path}: the corpus expects a refusal, but the value is {target!r}"
        )
        ledger.equal(f"{path}.expected_refusal", entry["expected_refusal"],
                     "NumericalRangeRefusal")
    else:
        assert kind == "value", (
            f"{path}: the corpus expects {entry['expected']!r}, but the value is {kind}"
        )
        ledger.number(f"{path}.expected", entry["expected"], target)


def _stable_form(statistic: str, points):
    """Tier 1 of a convex statistic: divide before accumulating, refusing a
    non-zero collapse to zero exactly as the accepted primitives do."""
    def divide(value: float, denominator: float):
        result = value / denominator
        if result == 0.0 and value != 0.0:
            return None
        return result

    if statistic == "midpoint":
        left, right = divide(points[0], 2.0), divide(points[1], 2.0)
        if left is None or right is None:
            return None
        total = left + right
    elif statistic == "triangular_mean":
        parts = [divide(point, 3.0) for point in points]
        if any(part is None for part in parts):
            return None
        total = parts[0] + parts[1] + parts[2]
    else:
        left, right = divide(points[0], 6.0), divide(points[2], 6.0)
        if left is None or right is None:
            return None
        total = left + points[1] * (2.0 / 3.0) + right
    return total if math.isfinite(total) else None


