def test_the_stage_a_verification_is_extended_and_nothing_was_dropped() -> None:
    """THE COUNT, PROVED RATHER THAN ASSERTED.

    Step 3 extends post-build verification, so the number must go up. What must
    NOT happen is an old check being replaced by a broader one to keep the total
    small, so every prior check is matched by description and the new ones are
    counted as an addition.

    Run WITHOUT the calculation contract, one prior check legitimately fails - the
    "only contract-declared Excel Tables exist" gate, because the artifact now
    carries five tables the caller did not declare. That is the gate working, not
    a regression, and it is why the comparison is on the check SET rather than on
    the pass count.
    """
    built = _built()
    before = verify_workbook(
        built["path"], built["spec"], built["contract"], built["drivers"],
        built["structure"],
    )
    after = verify_workbook(
        built["path"], built["spec"], built["contract"], built["drivers"],
        built["structure"], built["calc"],
    )

    def names(result) -> list[str]:
        return result.passed + [f.split(" -- ", 1)[0] for f in result.failures]

    prior, extended = names(before), names(after)
    assert len(prior) == 181, f"the Phase-4 baseline moved: {len(prior)}"
    assert set(prior) <= set(extended), sorted(set(prior) - set(extended))[:5]
    assert after.ok, after.report()
    assert len(extended) == 351, len(extended)
    assert len(extended) - len(prior) == 170


