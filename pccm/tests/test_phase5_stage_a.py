def test_the_renderer_does_not_import_the_analytical_oracle() -> None:
    """A structural guard: representation must not depend on calculation.

    Read from the AST, not from the text: this module's own docstring explains
    that it never imports the oracle, and a textual search would find that
    sentence and call it a violation.
    """
    import ast

    tree = ast.parse(
        (PCCM_ROOT / "builder" / "pccm_builder" / "calc_render.py").read_text(
            encoding="utf-8"
        )
    )
    imported: set[str] = set()
    called: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported |= {alias.name for alias in node.names}
        elif isinstance(node, ast.ImportFrom):
            imported.add(node.module or "")
            imported |= {alias.name for alias in node.names}
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            called.add(node.func.id)
    for banned in ("calc_oracle", ".calc_oracle", "calculate", "CalculationModel",
                   "calc_numeric"):
        assert banned not in imported, f"calc_render.py imports {banned}"
    assert "calculate" not in called


