def _verify_mutated(mutate) -> list[str]:
    """Build, mutate the saved workbook, re-verify. Returns the failures."""
    built = _built()
    directory = Path(tempfile.mkdtemp(prefix="pccm-step3-neg-"))
    try:
        workbook, _ = build_workbook(
            built["spec"], built["contract"], built["drivers"], built["structure"],
            built["calc"],
        )
        mutate(workbook["_Calc"], workbook)
        path = directory / "mutated.xlsx"
        workbook.save(path)
        workbook.close()
        result = verify_workbook(
            path, built["spec"], built["contract"], built["drivers"],
            built["structure"], built["calc"],
        )
        return result.failures
    finally:
        shutil.rmtree(directory, ignore_errors=True)


