_ARTIFACTS: dict[str, object] = {}


def _built() -> dict:
    """One real build, reused. Every assertion reads it back from DISK."""
    if _ARTIFACTS:
        return _ARTIFACTS
    directory = Path(tempfile.mkdtemp(prefix="pccm-step3-"))
    spec = load_spec(SPEC_PATH)
    contract = load_contract(CONTRACT_PATH)
    drivers = load_driver_contract(DRIVERS_PATH)
    structure = load_structure_contract(STRUCTURE_PATH)
    calc = load_calc_contract(CALC_PATH)

    workbook, _ = build_workbook(spec, contract, drivers, structure, calc)
    path = directory / "PCCM_stageA.xlsx"
    workbook.save(path)
    workbook.close()
    artifacts = emit_calc_artifacts(directory, spec, calc)

    _ARTIFACTS.update(
        directory=directory, path=path, spec=spec, contract=contract, drivers=drivers,
        structure=structure, calc=calc,
        module_text=artifacts.module_path.read_text(encoding="utf-8"),
        cases=json.loads(artifacts.cases_path.read_text(encoding="utf-8")),
        module_path=artifacts.module_path, cases_path=artifacts.cases_path,
    )
    return _ARTIFACTS


def _sheet():
    workbook = load_workbook(_built()["path"])
    return workbook, workbook["_Calc"]


def _module_constants() -> dict[str, str]:
    """`name -> literal text` parsed out of the generated .bas, as VBA would see it."""
    found: dict[str, str] = {}
    for line in _built()["module_text"].splitlines():
        stripped = line.strip()
        if not stripped.startswith("Public Const "):
            continue
        declaration = stripped[len("Public Const "):]
        name, _, rest = declaration.partition(" As ")
        _, _, value = rest.partition(" = ")
        found[name.strip()] = value.split("    ' ")[0].strip()
    return found


def _const_number(name: str) -> float:
    return float(_module_constants()[name])


def _const_string(name: str) -> str:
    raw = _module_constants()[name]
    assert raw.startswith('"') and raw.endswith('"'), f"{name} is not a String literal"
    return raw[1:-1].replace('""', '"')


