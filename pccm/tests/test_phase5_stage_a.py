def test_mutating_the_hash_authority_changes_the_projection() -> None:
    """NO SECOND SOURCE OF TRUTH, proved by moving the source.

    The generator is re-run against a patched `calc_fingerprint` module; if the
    emitted constant did not follow, the .bas would be carrying its own literal.
    """
    from pccm_builder import calc_emit, calc_fingerprint

    built = _built()
    original = calc_fingerprint.FP_BASE
    try:
        calc_fingerprint.FP_BASE = 137
        text = calc_emit.render_calc_contract_module(built["spec"], built["calc"])
        assert "Public Const FP_BASE As Long = 137" in text
    finally:
        calc_fingerprint.FP_BASE = original
    assert "Public Const FP_BASE As Long = 131" in (
        calc_emit.render_calc_contract_module(built["spec"], built["calc"])
    )


