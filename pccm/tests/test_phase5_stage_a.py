    document = _built()["cases"]
    ledger = _Ledger()
    _validate_corpus(ledger, document)

    expected = _expectation_paths(document)
    missing = sorted(expected - ledger.checked)
    extra = sorted(ledger.checked - expected)
    assert not missing, (
        f"{len(missing)} emitted expectations were never independently validated, "
        f"for example {missing[:5]}"
    )
    assert not extra, f"the ledger recorded paths the corpus does not contain: {extra[:5]}"
    assert len(expected) > 1900, len(expected)


