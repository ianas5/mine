# 5. THE INDEPENDENT ORACLE
# ---------------------------------------------------------------------------
# Exact rational arithmetic, written here from the plan's formulas. It shares no
# code with `calc_oracle.py`: it re-derives inflation factors, discount factors,
# Knom, Kpv, every driver amount, the annual series and the ten headline totals
# from the case's INPUT DATA alone. `Fraction` is exact and is test-only.
def _exact_statistic(distribution: str, minimum, most_likely, maximum):
    low, high = Fraction(minimum), Fraction(maximum)
    if distribution == "Uniform":
        central = mean = (low + high) / 2
    elif distribution == "Triangular":
        middle = Fraction(most_likely)
        central, mean = middle, (low + middle + high) / 3
    elif distribution == "Beta-PERT":
        middle = Fraction(most_likely)
        central, mean = middle, (low + 4 * middle + high) / 6
    else:
        raise AssertionError(distribution)
    return central, mean


def _exact_case(model: dict) -> dict:
    """Every published value of one case, in exact rationals."""
    timeline = model["timeline"]
    base, start, duration = (
        timeline["base_year"], timeline["start_year"], timeline["duration"]
    )
    years = [start + offset for offset in range(duration)]
    last = years[-1]

    factors: dict[str, dict[int, Fraction]] = {}
    for profile, rates in model["inflation"].items():
        running = Fraction(1)
        table = {base: Fraction(1)}
        for year in range(base + 1, last + 1):
            running = running * (1 + Fraction(rates[str(year)]))
            table[year] = running
        factors[profile] = table

    rate = Fraction(model["discount_rate"])
    discount = {1: Fraction(1)}
    for index in range(2, duration + 1):
        discount[index] = discount[index - 1] / (1 + rate)

    fx = {row["currency"]: Fraction(row["rate"])
          for row in model["fx"] if row["rate"] is not None}

    drivers = []
    for entry in sorted(model["cost_lines"] + model["risks"],
                        key=lambda d: d["permanent_id"]):
        is_risk = "probability" in entry
        weights = [Fraction(w) for w in entry["profile_weights"]]
        table = factors[entry["inflation_profile"]]
        rate_fx = fx[entry["currency"]]
        knom = rate_fx * sum(
            (weights[i] * table[years[i]] for i in range(duration)), Fraction(0)
        )
        kpv = rate_fx * sum(
            (weights[i] * table[years[i]] * discount[i + 1] for i in range(duration)),
            Fraction(0),
        )
        central, mean = _exact_statistic(
            entry["distribution"], entry["min_value"],
            entry.get("most_likely"), entry["max_value"],
        )
        multiplier = (
            Fraction(entry["probability"]) if is_risk else Fraction(entry["quantity"])
        )
        drivers.append({
            "permanent_id": entry["permanent_id"],
            "is_risk": is_risk,
            "central_value": central,
            "mean_value": mean,
            "knom": knom,
            "kpv": kpv,
            "weights": weights,
            "multiplier": multiplier,
            "table": table,
            "fx": rate_fx,
            "deterministic_nominal": Fraction(0) if is_risk else central * multiplier * knom,
            "deterministic_pv": Fraction(0) if is_risk else central * multiplier * kpv,
            "mean_basis_nominal": Fraction(0) if is_risk else mean * multiplier * knom,
            "mean_basis_pv": Fraction(0) if is_risk else mean * multiplier * kpv,
            "expected_risk_nominal": mean * multiplier * knom if is_risk else Fraction(0),
            "expected_risk_pv": mean * multiplier * kpv if is_risk else Fraction(0),
        })

    def total(key: str, risk: bool) -> Fraction:
        return sum((d[key] for d in drivers if d["is_risk"] is risk), Fraction(0))

    a_nom, a_pv = total("deterministic_nominal", False), total("deterministic_pv", False)
    c_nom, c_pv = total("mean_basis_nominal", False), total("mean_basis_pv", False)
    d_nom, d_pv = total("expected_risk_nominal", True), total("expected_risk_pv", True)

    annual = []
    for offset, year in enumerate(years):
        base_nom = sum(
            (d["mean_value"] * d["multiplier"] * d["fx"] * d["weights"][offset]
             * d["table"][year] for d in drivers if not d["is_risk"]),
            Fraction(0),
        )
        risk_nom = sum(
            (d["mean_value"] * d["multiplier"] * d["fx"] * d["weights"][offset]
             * d["table"][year] for d in drivers if d["is_risk"]),
            Fraction(0),
        )
        factor = discount[offset + 1]
        annual.append({
            "base_cost_nominal": base_nom, "expected_risk_nominal": risk_nom,
            "total_nominal": base_nom + risk_nom,
            "base_cost_pv": base_nom * factor, "expected_risk_pv": risk_nom * factor,
            "total_pv": (base_nom + risk_nom) * factor,
        })

    return {
        "drivers": drivers,
        "annual": annual,
        "totals": {
            "a_nom": a_nom, "a_pv": a_pv,
            "b_nom": c_nom - a_nom, "b_pv": c_pv - a_pv,
            "c_nom": c_nom, "c_pv": c_pv,
            "d_nom": d_nom, "d_pv": d_pv,
            "e_nom": c_nom + d_nom, "e_pv": c_pv + d_pv,
        },
    }


def test_every_emitted_number_is_confirmed_by_an_independent_exact_oracle() -> None:
    """THE GOLDEN-INDEPENDENCE PROOF.

    For every analytical case, every driver amount, every annual column and every
    headline total emitted into `phase5_cases.json` is re-derived here in exact
    rational arithmetic from the case's inputs, and compared. The emitted values
    came from `calc_oracle.py`; these came from the plan's formulas written out
    again. A defect in either shows up as a disagreement.
    """
    checked = 0
    for case in _built()["cases"]["plan_cases"]:
        if case["kind"] != "analytical":
            continue
        exact = _exact_case(case["model"])
        payload = case["expected"]

        assert len(payload["drivers"]) == len(exact["drivers"]), case["id"]
        for emitted, reference in zip(payload["drivers"], exact["drivers"]):
            assert emitted["permanent_id"] == reference["permanent_id"]
            # A field that does not apply to a driver kind is BLANK, never zero -
            # the same rule the contract states for the runtime table - so the
            # comparison asserts absence rather than a fabricated 0.
            cost_only = ("central_value", "deterministic_nominal", "deterministic_pv",
                         "mean_basis_nominal", "mean_basis_pv")
            risk_only = ("expected_risk_nominal", "expected_risk_pv")
            for key in ("mean_value", "knom", "kpv") + cost_only + risk_only:
                applies = not (
                    (reference["is_risk"] and key in cost_only)
                    or (not reference["is_risk"] and key in risk_only)
                )
                if not applies:
                    assert emitted[key] is None, (
                        f"case {case['id']} {emitted['permanent_id']} {key} is "
                        f"{emitted[key]!r}; a field that does not apply must be blank"
                    )
                    continue
                _close(emitted[key], float(reference[key]),
                       f"case {case['id']} {emitted['permanent_id']} {key}")
                checked += 1
            if not reference["is_risk"]:
                _close(
                    emitted["uncertainty_mean_shift_nominal"],
                    float(reference["mean_basis_nominal"]
                          - reference["deterministic_nominal"]),
                    f"case {case['id']} B nominal",
                )
                checked += 1

        assert len(payload["annual"]) == len(exact["annual"]), case["id"]
        for emitted, reference in zip(payload["annual"], exact["annual"]):
            for key in ("base_cost_nominal", "expected_risk_nominal", "total_nominal",
                        "base_cost_pv", "expected_risk_pv", "total_pv"):
                _close(emitted[key], float(reference[key]),
                       f"case {case['id']} year {emitted['calendar_year']} {key}")
                checked += 1

        for key, value in exact["totals"].items():
            _close(payload["totals"][key], float(value), f"case {case['id']} {key}")
            checked += 1

    assert checked > 400, f"only {checked} emitted numbers were independently checked"


