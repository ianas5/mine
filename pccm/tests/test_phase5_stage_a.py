def test_a_mutated_projected_tolerance_is_caught() -> None:
    """A projected constant that stops matching its authority fails the check."""
    import dataclasses

    from pccm_builder import calc_emit

    built = _built()
    calc = built["calc"]
    tampered = dataclasses.replace(
        calc, tolerances=dataclasses.replace(
            calc.tolerances, profiling_sum_absolute=1e-8
        )
    )
    text = calc_emit.render_calc_contract_module(built["spec"], tampered)
    value = next(
        line for line in text.splitlines()
        if line.startswith("Public Const TOL_PROFILING_SUM_ABSOLUTE")
    )
    assert "1e-08" in value
    assert value != next(
        line for line in built["module_text"].splitlines()
        if line.startswith("Public Const TOL_PROFILING_SUM_ABSOLUTE")
    )


