def test_the_projected_hash_constants_come_from_the_python_authority() -> None:
    """FP_BASE and the moduli are NOT in the YAML and must not be.

    `calc_fingerprint.py` is the reference implementation and owns the hash
    mathematics, so the generator imports it. Checked against the module's own
    attributes AND against the locked literals of plan section 11.4.
    """
    from pccm_builder import calc_fingerprint

    for name, locked in LOCKED_HASH_CONSTANTS.items():
        assert _const_number(name) == getattr(calc_fingerprint, name)
        assert _const_number(name) == locked
    assert _const_string("FP_STREAM_TAG") == calc_fingerprint.STREAM_TAG == "PCCM-FP"
    for index, section in enumerate(calc_fingerprint.SECTION_ORDER, start=1):
        assert _const_string(f"FP_SECTION_{index}") == section
    assert (
        CALC_PATH.read_text(encoding="utf-8").count("2147483647") == 0
    ), "a hash modulus leaked into the calculation contract, creating a second authority"


def test_mutating_the_hash_authority_changes_the_projection() -> None:
    """NO SECOND SOURCE OF TRUTH, proved by moving the source.

    The generator is re-run against a patched `calc_fingerprint` module; if the
    emitted constant did not follow, the .bas would be carrying its own literal.
    """
    from pccm_builder import calc_emit, calc_fingerprint

    built = _built()
    original = calc_fingerprint.FP_BASE
    try:
        calc_fingerprint.FP_BASE = 137
        text = calc_emit.render_calc_contract_module(built["spec"], built["calc"])
        assert "Public Const FP_BASE As Long = 137" in text
    finally:
        calc_fingerprint.FP_BASE = original
    assert "Public Const FP_BASE As Long = 131" in (
        calc_emit.render_calc_contract_module(built["spec"], built["calc"])
    )


