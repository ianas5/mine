# ---------------------------------------------------------------------------
# 5. THE INDEPENDENT REFERENCE, AND THE PATH LEDGER
# ---------------------------------------------------------------------------
# `phase5_cases.json` is generated BY the accepted oracle, so comparing it back to
# that oracle proves nothing. Everything below re-derives the corpus a second time,
# from the plan's rules, using only `Fraction`, plain Double arithmetic and locked
# literals written out in this file. It calls neither `calc_oracle.calculate`, nor
# `calc_cases.evaluate`, nor any production rescue helper.
#
# THE INVARIANT: no expected value may enter the Windows acceptance corpus without
# an independent Gate-A proof. That is enforced by a LEDGER rather than by a
# numeric floor - every expectation leaf in the JSON is enumerated, every check
# records the path it validated, and the two sets must be identical. A corpus that
# grows a new expected field without a matching check fails.
class _Ledger:
    """Records which expectation paths were independently validated."""

    def __init__(self) -> None:
        self.checked: set[str] = set()

    def mark(self, path: str) -> None:
        self.checked.add(path)

    def equal(self, path: str, actual, expected) -> None:
        assert actual == expected, f"{path}: emitted {actual!r}, independently {expected!r}"
        self.mark(path)

    def number(self, path: str, actual, expected) -> None:
        """A Double the corpus emitted, against the independently derived value.

        EXACT EQUALITY, with no tolerance and no scale. The independent reference
        deliberately reproduces the ACCEPTED EVALUATION SEMANTICS - tier 1's
        ordinary Double path where it succeeds, the exact rescue where it does
        not, the materialization boundaries, canonical driver order and the stable
        statistic forms - so it produces the very Double the corpus is expected to
        contain, not an idealised real number it should be near.

        THE EARLIER VERSION OF THIS METHOD WAS A DEFECT. It carried a `scale`
        taken from the largest magnitude anywhere in the payload and applied it to
        every field, so in a fixture with an annual row near `MAX_DOUBLE` the
        allowance was about `1.8e297` and `mean_value = 1e200` was accepted in
        place of `1.0`. Path coverage without discrimination proves nothing, and a
        C1-style conditioning scale belongs to RECONCILIATION - the question of
        whether two independently accumulated totals agree - never to the question
        of whether one emitted field equals its independently derived value.

        `None` (a field that does not apply to a driver kind) compares by equality
        too, so a blank can never be satisfied by a number or the reverse.
        """
        assert actual == expected, f"{path}: emitted {actual!r}, independently {expected!r}"
        self.mark(path)


def _leaf_paths(node, prefix: str):
    if isinstance(node, dict):
        for key in node:
            yield from _leaf_paths(node[key], f"{prefix}.{key}")
    elif isinstance(node, list):
        for index, item in enumerate(node):
            yield from _leaf_paths(item, f"{prefix}[{index}]")
    else:
        yield prefix


def _expectation_paths(document: dict) -> set[str]:
    """Every leaf the corpus asserts as an EXPECTATION.

    Model inputs (`model`, `terms`, `factors`, `points`), titles and prose are not
    expectations and are excluded; the whole `fingerprint` subtree is included,
    because every leaf under it is a locked value.
    """
    paths: set[str] = set()
    for index, case in enumerate(document["plan_cases"]):
        base = f"plan_cases[{index}]"
        if "expected" in case:
            paths |= set(_leaf_paths(case["expected"], f"{base}.expected"))
        if "expected_refusal" in case:
            paths.add(f"{base}.expected_refusal")
        for ordinal in range(len(case.get("statistics", []))):
            paths.add(f"{base}.statistics[{ordinal}].expected")
    for key in document["regression_vectors"]:
        for index, entry in enumerate(document["regression_vectors"][key]):
            base = f"regression_vectors.{key}[{index}]"
            if "expected" in entry:
                paths |= set(_leaf_paths(entry["expected"], f"{base}.expected"))
            if "expected_refusal" in entry:
                paths.add(f"{base}.expected_refusal")
    paths |= set(_leaf_paths(document["fingerprint"], "fingerprint"))
    return paths


# --- independent Double and exact-rational primitives -----------------------
_MAX_DOUBLE = 1.7976931348623157e308
_EXACT_MAX = Fraction(_MAX_DOUBLE)


def _rounded(value: Fraction):
    """The correctly rounded Double of an exact value, or `None` when there is
    none - out of range, or a non-zero value that rounds to zero."""
    if abs(value) > _EXACT_MAX:
        return None
    result = float(value)
    if result == 0.0 and value != 0:
        return None
    return result


def _double_product(factors):
    """Tier 1 of a product: left to right, refusing overflow and a non-zero
    collapse to zero. `None` means tier 1 produced no value."""
    result = 1.0
    for factor in factors:
        previous = result
        result = result * factor
        if not math.isfinite(result):
            return None
        if result == 0.0 and previous != 0.0 and factor != 0.0:
            return None
    return result


def _double_sum(terms):
    """Tier 1 of a sum: canonical order, left to right. `None` means it overflowed."""
    total = 0.0
    for term in terms:
        total = total + term
        if not math.isfinite(total):
            return None
    return total


def _exact_product(factors) -> Fraction:
    exact = Fraction(1)
    for factor in factors:
        exact = exact * Fraction(factor)
    return exact


def _value_of(factors):
    """One materialized product, under the accepted two tiers."""
    staged = _double_product(factors)
    if staged is not None:
        return staged
    return _rounded(_exact_product(factors))


def _series_of(groups):
    """One published series: the staged path, then the exact compound form.

    This is the accepted materialization rule written out from the specification -
    a per-driver contribution is not a published value, so the series falls back to
    one exact expression rather than refusing.
    """
    staged = [_double_product(group) for group in groups]
    if all(term is not None for term in staged):
        total = _double_sum(staged)
        if total is not None:
            return total
    exact = sum((_exact_product(group) for group in groups), Fraction(0))
    return _rounded(exact)


def _statistic_of(distribution: str, minimum, most_likely, maximum):
    """The plan's mandated stable forms, and the exact statistic they approximate.

    Returns `(double, exact)`: the stable form's own Double, and the exact rational
    the corpus is allowed to differ from by ordinary rounding.
    """
    low, high = float(minimum), float(maximum)
    if distribution == "Uniform":
        exact = (Fraction(low) + Fraction(high)) / 2
        if low == high:
            return low, exact                       # degenerate: exact by invariant
        return low / 2.0 + high / 2.0, exact
    middle = float(most_likely)
    if distribution == "Triangular":
        exact = (Fraction(low) + Fraction(middle) + Fraction(high)) / 3
        if low == middle == high:
            return low, exact
        return low / 3.0 + middle / 3.0 + high / 3.0, exact
    if distribution == "Beta-PERT":
        exact = (Fraction(low) + 4 * Fraction(middle) + Fraction(high)) / 6
        if low == middle == high:
            return low, exact
        return low / 6.0 + middle * (2.0 / 3.0) + high / 6.0, exact
    raise AssertionError(distribution)


_CENTRAL_BASIS = {"Triangular": "ML", "Beta-PERT": "ML", "Uniform": "Midpoint"}


def _reference_payload(model: dict) -> dict:
    """The COMPLETE expected payload of one analytical model, derived independently.

    Every field the corpus emits: the resolved FX map, the inflation factor rows,
    the discount series, all twenty-one driver fields plus the weights, all eight
    annual fields, and all ten headline totals.
    """
    timeline = model["timeline"]
    base, start, duration = (
        timeline["base_year"], timeline["start_year"], timeline["duration"]
    )
    years = [start + offset for offset in range(duration)]
    last = years[-1]

    # --- referenced-only resolution -----------------------------------------
    entries = sorted(model["cost_lines"] + model["risks"],
                     key=lambda d: d["permanent_id"])
    # REFERENCED-ONLY, strictly: a currency nothing points at is not resolved, and
    # the reporting currency is no exception when no driver uses it.
    referenced_currencies = {entry["currency"] for entry in entries}
    referenced_profiles = {entry["inflation_profile"] for entry in entries}
    rates = {row["currency"]: row["rate"] for row in model["fx"]}
    resolved_fx = {
        currency: float(rates[currency])
        for currency in sorted(referenced_currencies)
    }

    factors: dict[str, dict[int, float]] = {}
    inflation_rows: list[dict] = []
    for profile in sorted(referenced_profiles):
        declared = model["inflation"][profile]
        running = 1.0
        table = {base: 1.0}
        inflation_rows.append({"profile": profile, "calendar_year": base,
                               "annual_rate": None, "cumulative_factor": 1.0})
        for year in range(base + 1, last + 1):
            rate = float(declared[str(year)])
            running = running * (1.0 + rate)
            table[year] = running
            inflation_rows.append({"profile": profile, "calendar_year": year,
                                   "annual_rate": rate, "cumulative_factor": running})
        factors[profile] = table

    discount_rate = float(model["discount_rate"])
    discount = {1: 1.0}
    for index in range(2, duration + 1):
        discount[index] = discount[index - 1] / (1.0 + discount_rate)

    # --- per driver ----------------------------------------------------------
    drivers: list[dict] = []
    for entry in entries:
        is_risk = "probability" in entry
        weights = [float(w) for w in entry["profile_weights"]]
        table = factors[entry["inflation_profile"]]
        fx_rate = resolved_fx[entry["currency"]]

        nominal_terms = [[weights[i], table[years[i]]] for i in range(duration)]
        present_terms = [
            [weights[i], table[years[i]], discount[i + 1]] for i in range(duration)
        ]

        def factor(staged_groups, compound_groups):
            terms = [_double_product(group) for group in staged_groups]
            if all(term is not None for term in terms):
                total = _double_sum(terms)
                if total is not None:
                    scaled = total * fx_rate
                    if math.isfinite(scaled) and not (
                        scaled == 0.0 and total != 0.0 and fx_rate != 0.0
                    ):
                        return scaled
            exact = sum((_exact_product(group) for group in compound_groups),
                        Fraction(0))
            return _rounded(exact)

        knom = factor(nominal_terms, [[fx_rate] + group for group in nominal_terms])
        kpv = factor(present_terms, [[fx_rate] + group for group in present_terms])

        central, central_exact = _statistic_of(
            entry["distribution"], entry["min_value"],
            entry.get("most_likely"), entry["max_value"],
        )
        if entry["distribution"] != "Uniform":
            central, central_exact = float(entry["most_likely"]), Fraction(
                entry["most_likely"]
            )
            _, mean_exact = _statistic_of(
                entry["distribution"], entry["min_value"],
                entry["most_likely"], entry["max_value"],
            )
            mean, _ = _statistic_of(
                entry["distribution"], entry["min_value"],
                entry["most_likely"], entry["max_value"],
            )
        else:
            mean, mean_exact = central, central_exact

        multiplier = float(entry["probability"] if is_risk else entry["quantity"])
        shift = mean - central

        drivers.append({
            "permanent_id": entry["permanent_id"],
            "driver_kind": "Risk" if is_risk else "Cost Line",
            "distribution": entry["distribution"],
            "central_basis": _CENTRAL_BASIS[entry["distribution"]],
            "currency": entry["currency"],
            "fx_to_sar": fx_rate,
            "inflation_profile": entry["inflation_profile"],
            "quantity": None if is_risk else multiplier,
            "probability": multiplier if is_risk else None,
            "central_value": None if is_risk else central,
            "mean_value": mean,
            "knom": knom,
            "kpv": kpv,
            "deterministic_nominal":
                None if is_risk else _value_of([central, multiplier, knom]),
            "deterministic_pv":
                None if is_risk else _value_of([central, multiplier, kpv]),
            "mean_basis_nominal":
                None if is_risk else _value_of([mean, multiplier, knom]),
            "mean_basis_pv":
                None if is_risk else _value_of([mean, multiplier, kpv]),
            "uncertainty_mean_shift_nominal":
                None if is_risk else _value_of([shift, multiplier, knom]),
            "uncertainty_mean_shift_pv":
                None if is_risk else _value_of([shift, multiplier, kpv]),
            "expected_risk_nominal":
                _value_of([multiplier, mean, knom]) if is_risk else None,
            "expected_risk_pv":
                _value_of([multiplier, mean, kpv]) if is_risk else None,
            "weights": weights,
            "_exact_mean": mean_exact,
            "_exact_central": central_exact,
            "_multiplier": multiplier,
            "_fx": fx_rate,
            "_table": table,
        })

    # --- annual --------------------------------------------------------------
    annual: list[dict] = []
    for offset, year in enumerate(years):
        factor_of = discount[offset + 1]

        def groups(risk: bool, discounted: bool):
            built = []
            for driver in drivers:
                if (driver["driver_kind"] == "Risk") is not risk:
                    continue
                base_group = [
                    driver["mean_value"], driver["_multiplier"], driver["_fx"],
                    driver["weights"][offset], driver["_table"][year],
                ]
                built.append(base_group + [factor_of] if discounted else base_group)
            return built

        def staged_pv(risk: bool):
            """PV's tier 1 forms `nominal * discount` from the MATERIALIZED nominal."""
            terms = []
            for group in groups(risk, False):
                nominal = _double_product(group)
                if nominal is None:
                    return None
                present = _double_product([nominal, factor_of])
                if present is None:
                    return None
                terms.append(present)
            total = _double_sum(terms)
            return total

        def series(risk: bool, discounted: bool):
            if discounted:
                staged = staged_pv(risk)
                if staged is not None:
                    return staged
                exact = sum(
                    (_exact_product(group) for group in groups(risk, True)), Fraction(0)
                )
                return _rounded(exact)
            return _series_of(groups(risk, False))

        def total_series(discounted: bool):
            combined = groups(False, discounted) + groups(True, discounted)
            if discounted:
                terms = []
                for group in groups(False, False) + groups(True, False):
                    nominal = _double_product(group)
                    if nominal is None:
                        terms = None
                        break
                    present = _double_product([nominal, factor_of])
                    if present is None:
                        terms = None
                        break
                    terms.append(present)
                if terms is not None:
                    total = _double_sum(terms)
                    if total is not None:
                        return total
                exact = sum((_exact_product(group) for group in combined), Fraction(0))
                return _rounded(exact)
            return _series_of(combined)

        annual.append({
            "project_index": offset + 1,
            "calendar_year": year,
            "base_cost_nominal": series(False, False),
            "expected_risk_nominal": series(True, False),
            "total_nominal": total_series(False),
            "base_cost_pv": series(False, True),
            "expected_risk_pv": series(True, True),
            "total_pv": total_series(True),
        })

    # --- headline totals, accumulated in canonical driver order --------------
    def headline(key: str, risk: bool):
        terms = [d[key] for d in drivers
                 if (d["driver_kind"] == "Risk") is risk and d[key] is not None]
        total = _double_sum(terms)
        if total is not None:
            return total
        exact = sum((Fraction(term) for term in terms), Fraction(0))
        return _rounded(exact)

    a_nom, a_pv = headline("deterministic_nominal", False), headline("deterministic_pv", False)
    b_nom, b_pv = (headline("uncertainty_mean_shift_nominal", False),
                   headline("uncertainty_mean_shift_pv", False))
    c_nom, c_pv = headline("mean_basis_nominal", False), headline("mean_basis_pv", False)
    d_nom, d_pv = headline("expected_risk_nominal", True), headline("expected_risk_pv", True)

    def combined(cost_key: str, risk_key: str):
        terms = [d[cost_key] if d["driver_kind"] != "Risk" else d[risk_key]
                 for d in drivers]
        total = _double_sum([t for t in terms if t is not None])
        if total is not None:
            return total
        return _rounded(sum((Fraction(t) for t in terms if t is not None), Fraction(0)))

    return {
        "resolved_fx": resolved_fx,
        "inflation_factors": inflation_rows,
        "discount_factors": {str(k): v for k, v in sorted(discount.items())},
        "drivers": drivers,
        "annual": annual,
        "totals": {
            "a_nom": a_nom, "a_pv": a_pv, "b_nom": b_nom, "b_pv": b_pv,
            "c_nom": c_nom, "c_pv": c_pv, "d_nom": d_nom, "d_pv": d_pv,
            "e_nom": combined("mean_basis_nominal", "expected_risk_nominal"),
            "e_pv": combined("mean_basis_pv", "expected_risk_pv"),
        },
    }


