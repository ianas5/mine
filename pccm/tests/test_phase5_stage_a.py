#!/usr/bin/env python3
"""PCCM Phase 5 Gate-A Step-3 tests: Stage-A calculation workspace emission.

REPRESENTATION, NOT CALCULATION. Step 3 puts the physical `_Calc` workspace into
the generated workbook, projects the contract's runtime literals into
`modCalcContract.bas`, and emits the acceptance corpus `phase5_cases.json`.
Nothing in the build calculates a model into a cell.

--------------------------------------------------------------------------------
WHAT THIS FILE CHECKS, AND WHERE IT LOOKS
--------------------------------------------------------------------------------
The generated ARTIFACT, read back from disk. Proving that the contract says
`H:J` and that the renderer was called proves nothing about what shipped, so the
workbook is opened and its actual ListObject refs, cells, formats and validations
are asserted. The same for the two generated files: they are read as text and as
JSON, not as in-memory objects.

--------------------------------------------------------------------------------
GOLDEN INDEPENDENCE
--------------------------------------------------------------------------------
    hand-derived literal  ->  Python oracle  ->  phase5_cases.json  ->  later VBA

`phase5_cases.json` is generated BY the accepted oracle, so comparing it back to
that oracle would prove nothing. Every emitted number is therefore re-derived here
by a second, independently written route:

  * the plan's own section-23 literals, restated in this file;
  * `_reference_payload`, a complete second implementation of the accepted
    evaluation semantics, written from the plan's rules and sharing no code with
    `calc_oracle.py`. Because it reproduces those semantics rather than an
    idealised real-number formula, emitted Doubles are compared by EXACT equality;
  * the fingerprint reference stream, its 366-code-unit length, its digest and the
    eight probe digests, restated here as literals.

PROOF SCOPE: Linux, Python, openpyxl. NO VBA IS EXECUTED. NO WINDOWS TEST IS RUN.

Runs standalone or under pytest.
"""

