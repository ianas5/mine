def test_a_malformed_calculation_contract_fails_the_build_with_exit_code_two() -> None:
    """A calculation-contract-specific error, and a non-zero exit.

    The rule that rejects the mutation lives in the accepted Step-1 loader; what
    this proves is that the BUILDER consults it before emitting anything.
    """
    directory = Path(tempfile.mkdtemp(prefix="pccm-step3-bad-"))
    try:
        broken = directory / "calc_contract.yaml"
        text = CALC_PATH.read_text(encoding="utf-8")
        # A locked header spelling. The Step-1 loader owns the rule; what is proved
        # here is that the BUILDER runs it before emitting anything.
        broken.write_text(text.replace("header_row: 15", "header_row: 16", 1),
                          encoding="utf-8")
        completed = subprocess.run(
            [sys.executable, str(BUILD_SCRIPT), "--quiet",
             "--calc-contract", str(broken),
             "--out", str(directory / "out.xlsx")],
            capture_output=True, text=True, check=False,
        )
        assert completed.returncode == 2, completed.stdout + completed.stderr
        assert "CALCULATION CONTRACT ERROR" in completed.stderr, completed.stderr
        assert not (directory / "out.xlsx").exists(), (
            "a workbook was emitted despite an invalid calculation contract"
        )
    finally:
        shutil.rmtree(directory, ignore_errors=True)


