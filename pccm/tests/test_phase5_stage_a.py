def test_the_five_calculation_tables_exist_at_their_locked_physical_anchors() -> None:
    """Read out of the generated artifact, against literals restated here.

    Not "the contract says H:J and the renderer ran": the workbook is opened and
    its actual ListObject references are compared with the anchors the accepted
    design locks.
    """
    workbook, worksheet = _sheet()
    try:
        tables = worksheet.tables
        assert set(tables) == set(LOCKED_TABLE_ANCHORS), sorted(tables)
        for name, (header_row, first, last, width) in LOCKED_TABLE_ANCHORS.items():
            reference = tables[name].ref
            assert reference == f"{first}{header_row}:{last}{header_row + 1}", (
                f"{name} is at {reference}"
            )
            headers = [
                cell.value
                for cell in worksheet[f"{first}{header_row}:{last}{header_row}"][0]
            ]
            assert len(headers) == width, f"{name} is {len(headers)} columns wide"
            assert all(isinstance(h, str) and h for h in headers), headers
    finally:
        workbook.close()


