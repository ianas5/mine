def chart_polish_touches(path: str) -> bool:
    return path in _HUNKS


def strip_chart_polish(path: str, text: str) -> str:
    """`text` with the chart polish removed - all or none, exactly as the VBA
    layers: none of the fragments present returns the text unchanged, all of
    them present takes the layer off exactly, some of them raises."""
    hunks = _HUNKS.get(path, ())
    if not hunks:
        return text
    # PRESENT means the current fragment is there and the accepted one is not
    # - unless the hunk only ADDS lines, in which case its accepted fragment
    # is context that the current fragment contains. A hunk that only
    # REMOVES lines has a current fragment made of context, which the
    # accepted text carries too, around the lines it still has; there the
    # accepted fragment must be absent.
    present = [text.count(current) == 1
               and (text.count(accepted) == 0 or accepted in current)
               for current, accepted in hunks]
    if not any(present):
        return text
    if not all(present):
        missing = [index for index, found in enumerate(present) if not found]
        raise AssertionError(
            f"{path}: the chart polish is partly present (fragments {missing} absent); "
            "an undeclared edit sits inside the declared layer")
    for current, accepted in hunks:
        text = text.replace(current, accepted)
    return text


def undeclared_after_chart_polish(commit: str, changed: list[str], pccm_root) -> list[str]:
    """`changed` (pccm/-prefixed paths from `git diff --name-only commit`) with
    the declared chart-polish files taken out - after proving each reverses to
    `commit`'s bytes exactly, the reversal applied to BOTH sides so a pin that
    sits before or after the polish still compares the trees beneath it."""
    import subprocess
    from pathlib import Path as _Path
    root = _Path(pccm_root)
    # THE VBA MODULES ARE LEFT TO THE SHARED DECLARED-LAYER REVERSAL, which now
    # takes this polish off first and the layers beneath it after: a caller that
    # removed them here would skip those layers for the same file.
    polished = {f"pccm/{name}" for name in DECLARED_CHART_POLISH_CHANGES
                if not name.startswith("src/vba/")}
    for path in sorted(set(changed) & polished):
        name = path[len("pccm/"):]
        current = strip_chart_polish(name, (root / name).read_text(encoding="utf-8"))
        accepted = subprocess.run(["git", "show", f"{commit}:{path}"], cwd=root.parent,
                                  check=True, stdout=subprocess.PIPE).stdout.decode("utf-8")
        accepted = strip_chart_polish(name, accepted)
        assert current == accepted, f"{path} moved outside the declared chart polish"
    return [path for path in changed if path not in polished]
